"""Read each audit contract in its own interpreter; never combine ORM registries."""

import argparse
import ast
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CONTRACTS = {
    "identity": ("identity.events.audit_contract", "AUDIT_EVENT_TYPES"),
    "catalog": ("catalog.events.audit_contract", "AUDIT_EVENTS"),
    "accounting": ("accounting.events.audit_contract", "AUDIT_EVENTS"),
    "vouchers": ("vouchers.events.audit_contract", "AUDIT_EVENTS"),
    "reports": ("reports.events.audit_contract", "AUDIT_EVENTS"),
    "notification": ("notification.tasks.audit_publisher", "AUDIT_EVENT_TYPES"),
    "design": ("design.events.audit_contract", "AUDIT_EVENTS"),
}
CONSOLE = ROOT / "mfes/apps/console/app/lib/master-audit-entities.ts"


def contracts() -> dict[str, list[str]]:
    result = {"audit": ["audit.exported"]}
    for service, (module, name) in CONTRACTS.items():
        python = ROOT / "apis" / service / ".venv/Scripts/python.exe"
        process = subprocess.run(
            [
                str(python),
                "-c",
                f"import json; from {module} import {name}; print(json.dumps(sorted({name})))",
            ],
            capture_output=True,
            text=True,
            timeout=45,
            check=False,
        )
        if process.returncode:
            raise ValueError(f"Cannot read {service} audit contract")
        events = json.loads(process.stdout)
        if not 1 <= len(events) <= 1024 or any(
            not isinstance(event, str) or not re.fullmatch(r"[a-z][a-z0-9_.-]{0,59}", event)
            for event in events
        ):
            raise ValueError(f"Invalid {service} audit contract")
        result[service] = events
    return result


def entities(registered: dict[str, list[str]]) -> list[str]:
    # Retained pre-Vouchers history must remain selectable too.
    names = {
        "audit_event",
        "invoice",
        "payment",
        "credit_note",
        "report_run",
        "user_role",
        "item",
        "fiscal_period",
        "outbox_message",
        "company_feature",
    }
    for service, events in registered.items():
        if service not in {"identity", "audit"}:
            names.update(event.rsplit(".", 1)[0] for event in events)
    # Identity's public audit entity names intentionally differ from event prefixes.
    for source in (ROOT / "apis/identity/src/identity").rglob("*.py"):
        for node in ast.walk(ast.parse(source.read_text(encoding="utf-8-sig"))):
            if isinstance(node, ast.Call):
                for keyword in node.keywords:
                    if keyword.arg == "entity_type" and isinstance(keyword.value, ast.Constant):
                        value = keyword.value.value
                        if isinstance(value, str) and re.fullmatch(r"[a-z][a-z0-9_.]{0,79}", value):
                            names.add(value)
    return sorted(names)


def accounting_entities() -> dict[str, str]:
    python = ROOT / "apis/accounting/.venv/Scripts/python.exe"
    process = subprocess.run(
        [
            str(python),
            "-c",
            "import json; from accounting.resources import RESOURCES; "
            "from accounting.financial_resources import FINANCIAL_RESOURCES; "
            "print(json.dumps({s.path:'accounting.'+s.name "
            "for s in (*RESOURCES,*FINANCIAL_RESOURCES)}))",
        ],
        capture_output=True,
        text=True,
        timeout=45,
        check=False,
    )
    if process.returncode:
        raise ValueError("Cannot read Accounting native resource identities")
    return dict(json.loads(process.stdout))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write-console", action="store_true")
    parser.add_argument("--check-console", action="store_true")
    args = parser.parse_args()
    registered = contracts()
    if args.write_console or args.check_console:
        content = "// Generated by start/win/audit-contracts.py; do not edit.\n"
        content += (
            "export const MASTER_AUDIT_ENTITIES = "
            + json.dumps(entities(registered), indent=2)
            + " as const;\n"
        )
        content += (
            "export const ACCOUNTING_AUDIT_ENTITIES_BY_RESOURCE = "
            + json.dumps(accounting_entities(), indent=2, sort_keys=True)
            + " as const;\n"
        )
        if args.check_console:
            if not CONSOLE.exists() or CONSOLE.read_text(encoding="utf-8") != content:
                raise ValueError("Master audit subjects differ; regenerate them")
        else:
            CONSOLE.write_text(content, encoding="utf-8", newline="\n")
    else:
        print(json.dumps(registered))


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        raise SystemExit("Audit contracts failed: " + type(exc).__name__) from None
