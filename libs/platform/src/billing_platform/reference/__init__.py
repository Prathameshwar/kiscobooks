"""Tier-1 ISO reference data: the committed datasets and the seed that applies them.

``docs/tech-stack.md`` § *Reference tables* makes ``libs/platform`` the source of
truth for country, state and currency data, materialized into each service database
**by a seed, not by a migration**. A migration carrying content runs once, in one
environment, and cannot be corrected; a seed is re-runnable, so a corrected country
name reaches every environment on the next deploy.

The datasets under ``data/`` are generated by ``tools/generate_reference_data.py``
from ``pycountry``, CLDR and libphonenumber, and committed. That is what keeps a
seed reproducible and makes a change to a country name a reviewable diff rather
than a silent consequence of a dependency bump — and it keeps three ISO databases
out of seven services' runtime dependencies (CLAUDE.md §5.15).

Loading validates rather than trusts: unknown or missing keys, duplicate primary
keys and dangling references all fail here. A dataset regenerated against a newer
ISO edition that drops a column would otherwise surface as a ``TypeError`` halfway
through seeding a production database, with half the rows already written.
"""

from __future__ import annotations

import json
from functools import cache
from importlib import resources
from typing import Any, Final

from billing_platform.db.base import Base
from billing_platform.db.reference_models import Country, Currency, State

#: Seed order, which is also foreign-key order: ``country`` references
#: ``currency``, and ``state`` references ``country``.
DATASETS: Final[tuple[str, ...]] = ("currency", "country", "state")

MODELS: Final[dict[str, type[Base]]] = {
    "currency": Currency,
    "country": Country,
    "state": State,
}

#: ``{dataset: (column, referenced dataset)}`` — the references the loader closes
#: over. Checked in Python as well as by the database, because the seed inserts in
#: this order and a dangling reference should fail before the first write, not
#: partway through the third table.
_REFERENCES: Final[dict[str, tuple[str, str]]] = {
    "country": ("default_currency_code", "currency"),
    "state": ("country_code", "country"),
}


class ReferenceDataError(RuntimeError):
    """A committed dataset does not match the models it seeds."""


def _read(name: str) -> list[dict[str, Any]]:
    path = resources.files(__package__).joinpath("data", f"{name}.json")
    return list(json.loads(path.read_text(encoding="utf-8")))


def register_language() -> None:
    """Opt in only after the consuming service has migrated the language table."""
    from billing_platform.db.language import Language

    MODELS["language"] = Language


def _columns(name: str) -> set[str]:
    return {column.name for column in MODELS[name].__table__.columns}


def primary_key_column(name: str) -> str:
    """The single natural-code primary key column of a reference table."""
    keys = [str(column.name) for column in MODELS[name].__table__.columns if column.primary_key]
    if len(keys) != 1:  # pragma: no cover - guards a schema change, not a code path
        raise ReferenceDataError(f"{name} has a composite primary key: {keys}")
    return keys[0]


@cache
def _load_cached(name: str) -> tuple[dict[str, Any], ...]:
    if name not in MODELS:
        raise ReferenceDataError(f"unknown reference dataset {name!r}; known: {sorted(MODELS)}")

    rows = _read(name)
    expected = _columns(name)
    pk = primary_key_column(name)
    seen: set[str] = set()

    for index, row in enumerate(rows):
        if set(row) != expected:
            raise ReferenceDataError(
                f"{name}.json row {index} does not match the model: "
                f"missing={sorted(expected - set(row))}, unknown={sorted(set(row) - expected)}. "
                "Regenerate with tools/generate_reference_data.py."
            )
        key = row[pk]
        if key in seen:
            raise ReferenceDataError(f"{name}.json has a duplicate primary key {key!r}")
        seen.add(key)

    if name in _REFERENCES:
        column, target = _REFERENCES[name]
        known = {row[primary_key_column(target)] for row in _load_cached(target)}
        dangling = sorted({row[column] for row in rows} - known)
        if dangling:
            raise ReferenceDataError(
                f"{name}.json references {target} rows that do not exist: {dangling}"
            )

    return tuple(rows)


def load(name: str) -> list[dict[str, Any]]:
    """The validated rows of one dataset, as fresh dicts the caller may mutate.

    Copied on every call on purpose: the cache holds the parsed file, and handing
    out the cached dicts would let one caller's edit leak into the next.
    """
    return [dict(row) for row in _load_cached(name)]


def currencies() -> list[dict[str, Any]]:
    return load("currency")


def countries() -> list[dict[str, Any]]:
    return load("country")


def states() -> list[dict[str, Any]]:
    return load("state")


def load_all() -> dict[str, list[dict[str, Any]]]:
    """Every dataset, in seed order. Validates all three before returning any."""
    return {name: load(name) for name in DATASETS}


__all__ = [
    "DATASETS",
    "MODELS",
    "ReferenceDataError",
    "countries",
    "currencies",
    "load",
    "load_all",
    "primary_key_column",
    "states",
]
