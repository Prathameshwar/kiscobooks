"""Generate/check the exact Catalog audit event and safe-evidence matrix."""

import argparse
import json
from pathlib import Path

from catalog.events.audit_contract import AUDIT_EVENTS
from catalog.events.audit_policy import category, safe_fields

CONSOLE = (
    Path(__file__).resolve().parents[3] / "mfes/apps/console/app/lib/catalog-audit-entities.ts"
)
TARGET = Path(__file__).resolve().parents[1] / "contracts/audit-events.json"


def document() -> str:
    return (
        json.dumps(
            {
                event: {
                    "entity_type": event.rsplit(".", 1)[0],
                    "action": event,
                    "category": category(*event.rsplit(".", 1)),
                    "safe_fields": sorted(safe_fields(event.rsplit(".", 1)[0])),
                }
                for event in sorted(AUDIT_EVENTS)
            },
            indent=2,
        )
        + "\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = document()
    entities = sorted({name.rsplit(".", 1)[0] for name in AUDIT_EVENTS})
    typescript = (
        "// Generated by Catalog tools/export_audit_contract.py.\n"
        "export const CATALOG_AUDIT_ENTITIES = " + json.dumps(entities, indent=2) + " as const;\n"
    )

    if args.check:
        if (
            not TARGET.exists()
            or TARGET.read_text(encoding="utf-8") != expected
            or not CONSOLE.exists()
            or CONSOLE.read_text(encoding="utf-8") != typescript
        ):
            raise SystemExit("Catalog audit matrix differs; regenerate it")
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(expected, encoding="utf-8")
        CONSOLE.write_text(typescript, encoding="utf-8")
