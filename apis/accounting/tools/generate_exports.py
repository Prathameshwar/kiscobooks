"""Generate explicit typed export routes from the native resource registry."""

import argparse
from pathlib import Path

from accounting.resources import RESOURCES

TARGET = Path(__file__).resolve().parents[1] / "src/accounting/api/exports.py"


def document() -> str:
    result = '''"""Generated by tools.generate_exports: concrete contracts for master exports."""

import uuid
from typing import Annotated

from billing_platform.listing import Page
from fastapi import APIRouter, Depends, Query, Request
from fastapi.responses import JSONResponse
from sqlalchemy.ext.asyncio import AsyncSession

from accounting.api.auth import Access, access
from accounting.api.common import ERROR_RESPONSES, session, unique_query
from accounting.api.workflows import export_records
from accounting.schemas import masters as s
from accounting.schemas.query import MasterQuery

router = APIRouter(prefix="/v1/companies/{company_id}", responses=ERROR_RESPONSES)
'''
    for spec in RESOURCES:
        result += f"""

@router.get(
    "/exports/{spec.path}",
    response_model=Page[s.{spec.detail.__name__}],
    response_model_exclude_unset=True,
    dependencies=[Depends(unique_query)],
)
async def export_{spec.name}(
    company_id: uuid.UUID,
    request: Request,
    query: Annotated[MasterQuery, Query()],
    current: Access = Depends(access),
    db: AsyncSession = Depends(session),
) -> JSONResponse:
    return await export_records(
        company_id,
        "{spec.path}",
        request,
        query,
        current,
        db,
    )
"""
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = document()
    if args.check:
        if TARGET.read_text(encoding="utf-8") != generated:
            raise SystemExit("Accounting export routes are stale")
    else:
        TARGET.write_text(generated, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
