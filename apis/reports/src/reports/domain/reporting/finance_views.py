def registered_finance(
    code: str, output: tuple[Column, ...], layout: Layout
) -> tuple[View, ...] | None:
    if code not in FINANCE_VIEWS:
        return None
    title, keys = FINANCE_VIEWS[code]
    columns = {column.key: column for column in output}
    result: tuple[View, ...] = (
        View("default", title, tuple(columns[key] for key in keys), layout),
    )
    if code in {"OUTSTANDING_BILLS", "ADVANCES"}:
        result += (
            View(
                "party_balances",
                "Balances by party",
                (
                    Column("period", "Period"),
                    Column("account_code", "Account code"),
                    Column("account_name", "Account"),
                    Column("role", "Role"),
                    Column("currency", "Currency"),
                    Column("debt", "Debt", "MONEY", "currency"),
                    Column("unapplied_credit", "Unapplied credit", "MONEY", "currency"),
                    Column("net_debt", "Net debt", "MONEY", "currency"),
                ),
                "SUMMARY",
                calculation="party_balances",
            ),
        )
    return result
