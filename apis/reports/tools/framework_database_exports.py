def verify_files(csv_path, xlsx_path, columns, expected):
    """Compare every emitted cell; parsing retains one worksheet row at a time."""
    ns = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"
    count = 0
    with (
        csv_path.open(encoding="utf-8-sig", newline="") as stream,
        zipfile.ZipFile(xlsx_path) as book,
    ):
        reference = csv.reader(stream)
        assert next(reference) == [column.title for column in columns]
        names = sorted(
            (
                name
                for name in book.namelist()
                if name.startswith("xl/worksheets/sheet") and name.endswith(".xml")
            ),
            key=lambda name: int(name.rsplit("sheet", 1)[1].split(".")[0]),
        )
        for name in names:
            container = None
            with book.open(name) as sheet:
                # The archive is generated by this process, never supplied by a user.
                for event, element in ET.iterparse(sheet, events=("start", "end")):  # noqa: S314
                    if event == "start" and element.tag == ns + "sheetData":
                        container = element
                    if event != "end" or element.tag != ns + "row":
                        continue
                    if element.get("r") != "1":
                        cells = {cell.get("r").rstrip("0123456789"): cell for cell in element}
                        original = next(reference)
                        for index, column in enumerate(columns):
                            letters, position = "", index + 1
                            while position:
                                position, remainder = divmod(position - 1, 26)
                                letters = chr(65 + remainder) + letters
                            cell = cells.get(letters)
                            if cell is None:
                                assert original[index] == ""
                                continue
                            text = (
                                cell.find(ns + "is/" + ns + "t")
                                if cell.get("t") == "inlineStr"
                                else cell.find(ns + "v")
                            )
                            actual = "" if text is None or text.text is None else text.text
                            if column.kind in {"MONEY", "DECIMAL", "INTEGER"}:
                                assert Decimal(original[index]) == Decimal(actual)
                            elif column.kind == "DATE" and cell.get("t") != "inlineStr":
                                assert (
                                    original[index]
                                    == (
                                        dt.date(1899, 12, 30) + dt.timedelta(days=int(actual))
                                    ).isoformat()
                                )
                            else:
                                assert original[index] == actual
                        count += 1
                    assert container is not None
                    container.clear()
        assert next(reference, None) is None and count == expected
    return count


async def measure_exports(db, company, generation, query, transactions, output):
    output = output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    store = LocalArtifactStore(output / "private")
    context = await NativeContext.load(db, company, generation)
    query = RunRequest.model_validate(
        {key: value for key, value in query.model_dump().items() if key in RunRequest.model_fields}
    )
    columns = catalog().resolve(query.code).definition.views[0].columns
    budget = Budget(2 * transactions + 2, (2 * transactions + 2) * len(columns), 10 * 1024**3, 7200)
    samples, paths = [], {}
    for format_name, writer_type in (("CSV", CsvWriter), ("XLSX", XlsxWriter)):
        key = uuid.uuid4().hex
        path = store.begin(key)
        started = time.perf_counter()
        writer = writer_type(path, columns, budget)
        days = (END - BEGIN).days + 1
        cycles, extra = divmod(transactions, days)
        async for values in batches(db, context, query):
            for row in values:
                if row["row_kind"] == "OPENING":
                    assert row["balance"] == "0.0000"
                else:
                    number = int(row["number"].rsplit("/", 1)[-1])
                    day = number % days
                    rank = cycles * day + min(extra, day) + number // days + 1
                    expected = rank * 100 * (1 if row["account_id"] == str(identity(1, 0)) else -1)
                    assert row["balance"] == f"{expected}.0000"
            writer.append(values)
            if writer.count % 100000 < 200:
                print(
                    json.dumps(
                        {
                            "format": format_name,
                            "rows": writer.count,
                            "seconds": time.perf_counter() - started,
                        }
                    ),
                    flush=True,
                )
        await asyncio.to_thread(writer.finish)
        artifact = await asyncio.to_thread(store.publish, key, budget.bytes)
        store.discard_temporary(key)
        assert writer.count == 2 * transactions + 2
        sample = {
            "format": format_name,
            "rows": writer.count,
            "columns": len(columns),
            "seconds": time.perf_counter() - started,
            "peak_rss_bytes": peak_rss(),
            "artifact_key": key,
            "content_hash": artifact.content_hash,
            "byte_count": artifact.byte_count,
        }
        samples.append(sample)
        paths[format_name] = store.root / "objects" / key
        print(json.dumps({"database_export": sample}), flush=True)
    count = await asyncio.to_thread(
        verify_files, paths["CSV"], paths["XLSX"], columns, 2 * transactions + 2
    )
    result = {
        "samples": samples,
        "verified_artifact_rows": count,
        "boundary": "guarded native retained ledger batches to durable files; "
        "no HTTP, authority, queue or production ingestion",
    }
    (output / "database-exports.json").write_text(
        json.dumps(result, indent=2) + "\n", encoding="utf-8"
    )
    return result
