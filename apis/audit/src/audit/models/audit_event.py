"""The one table this service owns (docs/audit.md §3).

Append-only by database grant (§4.1), never edited or deleted row-by-row. It carries
the full documented event shape; the columns the current emit contract
(``billing_platform.outbox.audit_payload``) does not yet populate are **nullable** and
stay null until that contract is enriched (decision log, docs/audit.md §8).

Two invariants are structural, not conventional:

* **Composite primary key ``(occurred_at, id)``.** ``occurred_at`` is the RANGE
  partition column (§6), and MySQL requires every unique key on a partitioned table to
  include the partition column. This cannot change later without a full table rebuild,
  so it is fixed in the first migration.
* **Per-tenant hash chain** — ``prev_hash`` is the previous row's ``row_hash`` for the
  same tenant, ``row_hash`` covers the row's content plus ``prev_hash`` (§4.2). The
  single ingestion consumer assigns ``sequence`` and computes both.
"""

from __future__ import annotations

import datetime as dt
import uuid
from typing import Any

from billing_platform.db.base import MARIADB_TABLE_ARGS, Base
from billing_platform.db.mixins import TenantMixin
from billing_platform.db.types import UtcDateTime, Uuid7
from sqlalchemy import BINARY, JSON, BigInteger, Index, String
from sqlalchemy.orm import Mapped, mapped_column


class AuditEvent(TenantMixin, Base):
    """One recorded state change or audited read.

    ``TenantMixin`` (not ``IdMixin``) because the primary key is composite and defined
    here; the mixin still subjects every read to the session-level tenant filter, which
    is what keeps one tenant's trail invisible to another (CLAUDE.md §5.3).
    """

    __tablename__ = "audit_event"
    __table_args__ = (
        # The audit-trail read: newest-first within a tenant, optionally by entity.
        Index("ix_audit_event_tenant_id_occurred_at", "tenant_id", "occurred_at"),
        Index(
            "ix_audit_event_tenant_id_entity_type_entity_id",
            "tenant_id",
            "entity_type",
            "entity_id",
        ),
        # The activity feed and the security surface both filter by category within a
        # tenant; the company scope check narrows by company.
        Index(
            "ix_audit_event_tenant_id_category_occurred_at",
            "tenant_id",
            "category",
            "occurred_at",
        ),
        Index(
            "ix_audit_event_tenant_id_company_id_occurred_at",
            "tenant_id",
            "company_id",
            "occurred_at",
        ),
        # The chain writer reads the tenant's current head to extend the chain.
        Index("ix_audit_event_tenant_id_sequence", "tenant_id", "sequence"),
        MARIADB_TABLE_ARGS,
    )

    #: Leads the composite PK and is the RANGE partition key: the *source* timestamp set
    #: by the emitting service at the moment of the change (§2.2), never the consumer's
    #: receipt time. Leading the PK also clusters InnoDB in time order, matching the
    #: newest-first read.
    occurred_at: Mapped[dt.datetime] = mapped_column(UtcDateTime, primary_key=True)
    #: The other half of the PK; generated by the consumer, time-ordered (UUIDv7).
    id: Mapped[uuid.UUID] = mapped_column(Uuid7, primary_key=True)

    #: Per-tenant monotonic counter assigned by the single writer. With the hash chain
    #: it makes a deleted row detectable as a gap even if the chain were recomputed.
    sequence: Mapped[int] = mapped_column(BigInteger, nullable=False)

    # -- actor (PII-free: references only, never a name/email/phone — §5.2) ------------
    actor_type: Mapped[str | None] = mapped_column(String(32), nullable=True)
    actor_user_id: Mapped[uuid.UUID | None] = mapped_column(Uuid7, nullable=True)
    on_behalf_of_user_id: Mapped[uuid.UUID | None] = mapped_column(Uuid7, nullable=True)
    actor_ip: Mapped[str | None] = mapped_column(String(45), nullable=True)
    actor_user_agent: Mapped[str | None] = mapped_column(String(400), nullable=True)
    api_client_id: Mapped[uuid.UUID | None] = mapped_column(Uuid7, nullable=True)

    # -- scope -------------------------------------------------------------------------
    company_id: Mapped[uuid.UUID | None] = mapped_column(Uuid7, nullable=True)
    department_id: Mapped[uuid.UUID | None] = mapped_column(Uuid7, nullable=True)

    # -- what happened -----------------------------------------------------------------
    category: Mapped[str] = mapped_column(String(20), nullable=False)
    action: Mapped[str] = mapped_column(String(60), nullable=False)
    entity_type: Mapped[str] = mapped_column(String(80), nullable=False)
    entity_id: Mapped[uuid.UUID | None] = mapped_column(Uuid7, nullable=True)
    #: Changed fields only, ``{field: {from, to}}`` — never a token, bank account,
    #: password, or full tax id (invariant 9, CLAUDE.md §5.11).
    changes: Mapped[dict[str, Any] | None] = mapped_column(JSON, nullable=True)
    context: Mapped[dict[str, Any] | None] = mapped_column(JSON, nullable=True)
    reason: Mapped[str | None] = mapped_column(String(500), nullable=True)

    # -- correlation -------------------------------------------------------------------
    source_service: Mapped[str | None] = mapped_column(String(40), nullable=True)
    trace_id: Mapped[str | None] = mapped_column(String(32), nullable=True)
    request_id: Mapped[str | None] = mapped_column(String(64), nullable=True)
    #: The outbox ``message_id``; the dedupe key (§2.2). Deduplication itself is keyed in
    #: ``processed_message``; this column keeps the provenance on the row.
    message_id: Mapped[uuid.UUID] = mapped_column(Uuid7, nullable=False)

    # -- integrity (§4.2) --------------------------------------------------------------
    #: NULL only on the first event of a tenant's chain.
    prev_hash: Mapped[bytes | None] = mapped_column(BINARY(32), nullable=True)
    row_hash: Mapped[bytes] = mapped_column(BINARY(32), nullable=False)

    #: The consumer's receipt time — distinct from ``occurred_at`` so replica lag and
    #: redelivery reordering are visible rather than hidden.
    ingested_at: Mapped[dt.datetime] = mapped_column(UtcDateTime, nullable=False)
